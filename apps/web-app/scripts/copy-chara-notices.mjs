#!/usr/bin/env node
/**
 * Generate public/licenses/xivcharakit.txt: the license notice for the .chara
 * reader the web app ships.
 *
 * The app reads .chara character files with xivcharakit, which reaches the
 * bundle through @xivdyetools/core. Its MIT license and third-party notices
 * have to travel with it, so this script copies the INSTALLED package's
 * `dist/LICENSE` and `dist/THIRD_PARTY_NOTICES.md` byte for byte under a short
 * fixed header, and the About modal links the result.
 *
 * The package is located THROUGH core, because that is the copy the bundle
 * actually contains: resolve `@xivdyetools/core/package.json` from the web app
 * (core exports it), take the real path of core's directory, then core's own
 * `node_modules/xivcharakit`. pnpm's strict layout gives the web app no
 * xivcharakit of its own, and the package's exports map exposes neither
 * `./package.json` nor a `require` condition, so neither a hoisted path nor
 * `require.resolve('xivcharakit/...')` is a sound way to find it.
 *
 * The output is committed and regenerated by `npm run build`; the drift test in
 * copy-chara-notices.test.js fails when the committed file no longer matches
 * the installed package.
 *
 * Usage: node scripts/copy-chara-notices.mjs   (or `npm run copy-chara-notices`)
 *
 * @entrypoint run by the web app's `build` and `copy-chara-notices` package.json scripts; its drift test is the only importer, by design.
 */

import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PACKAGE_NAME = 'xivcharakit';
const CORE_NAME = '@xivdyetools/core';

/** Where the notice lands, relative to the web app's package directory. */
export const NOTICE_OUTPUT = 'public/licenses/xivcharakit.txt';

const DEFAULT_APP_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Decodes strictly: a byte sequence that is not UTF-8 must fail, not turn into U+FFFD. */
const utf8 = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true });

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/**
 * Find the xivcharakit package that @xivdyetools/core depends on, starting from
 * a web app directory. Returns real (symlink-resolved) paths.
 */
export function locateCharaKit(appDir = DEFAULT_APP_DIR) {
  const requireFromApp = createRequire(join(appDir, 'package.json'));
  let corePackageJson;
  try {
    corePackageJson = requireFromApp.resolve(`${CORE_NAME}/package.json`);
  } catch (error) {
    throw new Error(
      `copy-chara-notices: cannot resolve ${CORE_NAME}/package.json from ${appDir} (${error.message}); run pnpm install`
    );
  }
  const corePackageDir = realpathSync(dirname(corePackageJson));
  const pinnedVersion = readJson(join(corePackageDir, 'package.json')).dependencies?.[PACKAGE_NAME];
  if (typeof pinnedVersion !== 'string' || pinnedVersion === '') {
    throw new Error(
      `copy-chara-notices: ${CORE_NAME} (${corePackageDir}) does not declare ${PACKAGE_NAME} in its dependencies, so there is no reader notice to ship`
    );
  }
  const linked = join(corePackageDir, 'node_modules', PACKAGE_NAME);
  if (!existsSync(join(linked, 'package.json'))) {
    throw new Error(
      `copy-chara-notices: ${PACKAGE_NAME} is not installed for ${CORE_NAME} (looked in ${linked}); run pnpm install`
    );
  }
  return { packageDir: realpathSync(linked), corePackageDir, pinnedVersion };
}

function readNoticeFile(packageDir, relative) {
  const file = join(packageDir, relative);
  if (!existsSync(file)) {
    throw new Error(
      `copy-chara-notices: ${PACKAGE_NAME} ships no ${relative} (looked for ${file}); the web app cannot publish its license notice without it`
    );
  }
  try {
    return utf8.decode(readFileSync(file));
  } catch {
    throw new Error(`copy-chara-notices: ${PACKAGE_NAME} ${relative} is not valid UTF-8, so it cannot be copied verbatim`);
  }
}

/** Ends `text` with exactly the newline it needs to put the next line on a line of its own. */
const lineBreakAfter = (text) => (text.endsWith('\n') ? '' : '\n');

/**
 * Build the notice text for the xivcharakit package at `packageDir`. Reads, never
 * writes. `pinnedVersion` defaults to the version @xivdyetools/core pins; the
 * installed package must be named xivcharakit and carry exactly that version.
 */
export function buildCharaNotice(packageDir, { pinnedVersion } = {}) {
  const pin = pinnedVersion ?? locateCharaKit().pinnedVersion;
  const manifestFile = join(packageDir, 'package.json');
  if (!existsSync(manifestFile)) {
    throw new Error(`copy-chara-notices: no package.json in ${packageDir}`);
  }
  const manifest = readJson(manifestFile);
  if (manifest.name !== PACKAGE_NAME) {
    throw new Error(
      `copy-chara-notices: expected package "${PACKAGE_NAME}" in ${packageDir}, found "${manifest.name}"`
    );
  }
  if (manifest.version !== pin) {
    throw new Error(
      `copy-chara-notices: ${PACKAGE_NAME} ${manifest.version} is installed but ${CORE_NAME} pins ${pin}; run pnpm install so the shipped notice matches the shipped code`
    );
  }

  const license = readNoticeFile(packageDir, 'dist/LICENSE');
  const notices = readNoticeFile(packageDir, 'dist/THIRD_PARTY_NOTICES.md');

  const header = [
    `${PACKAGE_NAME} ${pin}: license and third-party notices`,
    '',
    `XIV Dye Tools reads .chara character files with the open-source ${PACKAGE_NAME}`,
    `library, version ${pin}, which the app bundles through ${CORE_NAME}.`,
    'Its license and third-party notices follow, copied verbatim from the package.',
    '',
  ].join('\n');

  return (
    `${header}\n` +
    `======== ${PACKAGE_NAME} ${pin}: dist/LICENSE ========\n` +
    license +
    lineBreakAfter(license) +
    '\n' +
    `======== ${PACKAGE_NAME} ${pin}: dist/THIRD_PARTY_NOTICES.md ========\n` +
    notices +
    lineBreakAfter(notices)
  );
}

/** Locate the package through core, build the notice and write it under `appDir`. */
export function writeCharaNotice({ appDir = DEFAULT_APP_DIR } = {}) {
  const { packageDir, pinnedVersion } = locateCharaKit(appDir);
  const text = buildCharaNotice(packageDir, { pinnedVersion });
  const outFile = join(appDir, NOTICE_OUTPUT);
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  return { outFile, text };
}

// Guarded so importing this module from tests does not run the CLI. Under vitest
// process.argv[1] is the vitest binary, so this is false.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { outFile } = writeCharaNotice();
    console.log(`copy-chara-notices: wrote ${outFile}`);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
